#!/usr/bin/env python3
"""Builds docs/comparison.md from the runners' results (conformance/runners/*/results.jsonl).

Each runner prints one JSON line per case: {"id", "result": valid|invalid|unsupported|crash, "detail"}.
A library "agrees" with a case when it accepts a valid message, or rejects (invalid or unsupported)
one that should be rejected. When a library doesn't support a message version at all, cases for that
message are counted as "not supported" instead of right or wrong.
"""
import json
import pathlib
from collections import OrderedDict

HERE = pathlib.Path(__file__).parent
DOCS = HERE.parent / "docs"

LIBRARIES = OrderedDict([
    ("dotnet-iso20022kit", {
        "name": "Iso20022Kit (.NET)", "version": "0.1.0 (this repository)",
        "how": "`Iso20022.Validate`: official XSD, then business rules.",
    }),
    ("java-prowide", {
        "name": "Prowide ISO 20022 (Java)", "version": "pw-iso20022 SRU2025-10.4.0",
        "how": "`AbstractMX.parse`. The open-source edition parses but does not validate (validation is in Prowide's commercial SDK), so here \"accepted\" means \"parsed\".",
    }),
    ("go-moov", {
        "name": "Moov iso20022 (Go)", "version": "v0.2.1 (latest release; main branch gives the same results)",
        "how": "`document.ParseIso20022Document` then `Validate()`.",
    }),
    ("rust-mx20022", {
        "name": "mx20022 (Rust)", "version": "0.3.0 (crates 0.3.2)",
        "how": "`detect_message_type`, `from_str_in_envelope` into the generated pacs.008.001.08 type, then `validate_message()` (XSD constraints). Has no camt.053.001.08 type (it has 001.11). Its separate scheme validators (FedNow, SEPA, CBPR+) were not run.",
    }),
])

CATEGORY_ORDER = ["valid", "schema", "business", "wellformed", "unsupported", "security"]


def load_results(runner):
    path = HERE / "runners" / runner / "results.jsonl"
    return {r["id"]: r for r in (json.loads(l) for l in path.read_text().splitlines() if l.strip())}


def verdict(case, results, unsupported_messages):
    """agree | disagree | n/a | inconclusive"""
    r = results[case["id"]]["result"]
    if case["category"] in ("valid", "schema", "business") and r == "unsupported" and case["message"] in unsupported_messages:
        return "n/a"
    if r == "crash":
        return "disagree"
    accepted = r == "valid"
    if not case["expect"]["valid"] and not accepted and case["category"] in ("schema", "business") and "base" in case:
        # rejecting a broken message only shows the library caught the change if it accepts the original
        if results[case["base"]]["result"] != "valid":
            return "inconclusive"
    return "agree" if accepted == case["expect"]["valid"] else "disagree"


def main():
    suite = json.loads((HERE / "suite.json").read_text())
    cases = suite["cases"]
    results = {k: load_results(k) for k in LIBRARIES}
    unsupported = {
        k: {c["message"] for c in cases if c["category"] == "valid" and results[k][c["id"]]["result"] == "unsupported" and c["message"]}
        for k in LIBRARIES
    }
    # a message version is "not supported" by a library only if it reports every valid case of it as unsupported
    for k in LIBRARIES:
        unsupported[k] = {m for m in unsupported[k]
                          if all(results[k][c["id"]]["result"] == "unsupported" for c in cases if c["message"] == m and c["category"] == "valid" and "envelope" not in c["id"])}

    lines = []
    w = lines.append
    w("# How ISO 20022 libraries handle the conformance suite")
    w("")
    w(f"The [conformance suite](../conformance/README.md) ({len(cases)} cases: valid messages, and messages broken in one way each) run against four open-source libraries. "
      "Generated by `conformance/compare.py` from the runners in `conformance/runners/`; rerun them to update this page.")
    w("")
    w("This measures one thing: whether a library accepts what it should and rejects what it should, for pacs.008.001.08 and camt.053.001.08. "
      "The suite was written alongside Iso20022Kit, so Iso20022Kit passing all of it is expected and proves little; the useful part is what it shows about the others, and new cases from other people are the best way to test Iso20022Kit itself. "
      "It is not a ranking of the libraries overall. They differ in scope: some cover hundreds of messages, translate from the old MT format, or check scheme rules (CBPR+, FedNow, SEPA) that this suite doesn't test.")
    w("")
    w("## Libraries and versions")
    w("")
    w("| Library | Version | What \"accepted\" means here |")
    w("|---|---|---|")
    for k, lib in LIBRARIES.items():
        w(f"| {lib['name']} | {lib['version']} | {lib['how']} |")
    w("")
    w("## Results by category")
    w("")
    w("Each cell: cases where the library reached the expected verdict / cases it could be judged on. "
      "\"n/s\": the library doesn't support that message version. "
      "\"inconclusive\": the library rejected a broken message, but it also rejects the valid message that case was made from, so the rejection doesn't show it caught the problem.")
    w("")
    w("| Category | Cases | " + " | ".join(lib["name"] for lib in LIBRARIES.values()) + " |")
    w("|---|---|" + "---|" * len(LIBRARIES))
    for cat in CATEGORY_ORDER:
        in_cat = [c for c in cases if c["category"] == cat]
        cells = []
        for k in LIBRARIES:
            vs = [verdict(c, results[k], unsupported[k]) for c in in_cat]
            judged = [v for v in vs if v not in ("n/a", "inconclusive")]
            na = vs.count("n/a")
            inc = vs.count("inconclusive")
            cell = f"{sum(v == 'agree' for v in judged)} / {len(judged)}" if judged else ("n/s" if na == len(vs) else "–")
            notes = [f"{na} n/s"] * bool(na and judged) + [f"{inc} inconclusive"] * bool(inc)
            if notes:
                cell += f" ({', '.join(notes)})"
            cells.append(cell)
        w(f"| {cat} | {len(in_cat)} | " + " | ".join(cells) + " |")
    w("")
    w("## Case by case")
    w("")
    w("✓ expected verdict · ✗ different verdict · ? rejected, but the valid original is rejected too · – message version not supported. Each library's own message for every case is in `conformance/runners/*/results.jsonl`.")
    w("")
    w("| Case | Expected | " + " | ".join(lib["name"].split(" (")[0] for lib in LIBRARIES.values()) + " |")
    w("|---|---|" + "---|" * len(LIBRARIES))
    for c in sorted(cases, key=lambda c: (CATEGORY_ORDER.index(c["category"]), c["id"])):
        marks = []
        for k in LIBRARIES:
            v = verdict(c, results[k], unsupported[k])
            marks.append({"agree": "✓", "disagree": "✗", "n/a": "–", "inconclusive": "?"}[v])
        w(f"| `{c['id']}` | {'accept' if c['expect']['valid'] else 'reject'} | " + " | ".join(marks) + " |")
    w("")
    w("## Findings")
    w("")
    w("Checked against each project's source before being written here.")
    w("")
    w("- **Moov iso20022 rejects valid messages that use an \"either/or\" account identifier.** In `pkg/pacs_v08`, `AccountIdentification4Choice` declares `Othr` as a non-pointer struct, so a pacs.008.001.08 account given by IBAN fails `Validate()` on the empty `Othr/Id`. In `pkg/camt_v08` both `IBAN` and `Othr` are non-pointer fields, so every camt.053.001.08 account fails one of them. Minimal reproduction: the suite's `pacs008-valid-minimal` (IBAN account) is rejected, while the same message with the account given as `<Othr><Id>…</Id></Othr>`, or with no account, is accepted. The same pattern likely affects other generated choice types; the last commit on the main branch is from January 2023.")
    w("- **mx20022 doesn't check minimum/maximum values or date validity.** Its code generator skips `minInclusive`/`maxInclusive` (\"require numeric parsing — deferred\" in `crates/mx20022-codegen/src/emit/validate.rs`), so a negative `IntrBkSttlmAmt` passes, and `ISODate` is a plain string, so `2026-13-40` passes. It also accepts elements in the wrong order and unknown elements, since it deserialises with serde rather than validating against the XSD. Confirmed on the main branch (October 2026).")
    w("- **Prowide's open-source edition is a parser, not a validator.** It accepts every structurally broken message in the suite; its schema validation is part of the commercial edition, which wasn't tested.")
    w("- **mx20022 0.3.0 doesn't read a message inside an envelope with an `AppHdr`**: it detects the header's namespace (head.001) instead of the Document's. Its main branch documents that the Document namespace now wins.")
    w("- **Every library refuses the two DTD entity attacks** (XXE and \"billion laughs\") instead of expanding them.")
    w("- **Business rules** (totals, statement balances, ISO 4217 decimals, IBAN check digits) are only checked by Iso20022Kit among these runs. mx20022's scheme validators may cover some of them for CBPR+, FedNow and SEPA messages; they weren't part of this run.")
    w("")
    (DOCS / "comparison.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("docs/comparison.md written")
    for k, lib in LIBRARIES.items():
        vs = [verdict(c, results[k], unsupported[k]) for c in cases]
        print(f"  {lib['name']}: {vs.count('agree')} agree, {vs.count('disagree')} disagree, {vs.count('inconclusive')} inconclusive, {vs.count('n/a')} n/s")


if __name__ == "__main__":
    main()
