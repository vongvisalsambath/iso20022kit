#!/usr/bin/env bash
# Regenerates the C# types in src/Iso20022Kit/Generated from the schemas in /schemas.
# Needs the XmlSchemaClassGenerator tool: dotnet tool restore (see .config/dotnet-tools.json).
set -euo pipefail
cd "$(dirname "$0")/.."
out=src/Iso20022Kit/Generated
rm -f "$out"/*.cs
for pair in "pacs.008.001.08:Pacs008V08" "camt.053.001.08:Camt053V08"; do
  id=${pair%%:*}; ns=${pair##*:}
  dotnet xscgen -0 --nc --csm=Public \
    -n "urn:iso:std:iso:20022:tech:xsd:$id=Iso20022Kit.Messages.$ns" -o "$out" "schemas/$id.xsd"
done
for f in "$out"/*.cs; do
  { printf '// <auto-generated>\n// Generated by XmlSchemaClassGenerator from the official ISO 20022 schema in /schemas. Do not edit: run scripts/generate.sh.\n// </auto-generated>\n#nullable disable\n#pragma warning disable\n'; cat "$f"; } > "$f.tmp" && mv "$f.tmp" "$f"
done
echo "Generated: $(ls "$out")"
